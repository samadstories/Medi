val LocalStrings = staticCompositionLocalOf { StringsEn }

fun resolveStrings(
    language: AppLanguage,
    overrides: List<TranslationOverride> = emptyList()
): LocalizedStrings {
    val base = when (language) {
        AppLanguage.EN -> StringsEn
        AppLanguage.HI -> StringsHi
        AppLanguage.BN -> StringsBn
    }
    if (overrides.isEmpty()) return base
    val map = overrides.associateBy { it.key }
    return base.copy(
        appTagline = map["app_tagline"]?.get(language) ?: base.appTagline,
        safetyBannerTitle = map["safety_banner_title"]?.get(language) ?: base.safetyBannerTitle,
        safetyBannerBody = map["safety_banner_body"]?.get(language) ?: base.safetyBannerBody
    )
}
